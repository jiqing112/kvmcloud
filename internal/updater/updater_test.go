type tarEntry struct{ name, body string }

// buildTarGz 内存构造 tar.gz 归档（zip-slip 测试用），返回落盘路径。
func buildTarGz(t *testing.T, dir, file string, entries []tarEntry) string {
	t.Helper()
	var buf bytes.Buffer
	gz := gzip.NewWriter(&buf)
	tw := tar.NewWriter(gz)
	for _, e := range entries {
		hdr := &tar.Header{Name: e.name, Mode: 0o755, Size: int64(len(e.body))}
		if err := tw.WriteHeader(hdr); err != nil {
			t.Fatal(err)
		}
		if _, err := tw.Write([]byte(e.body)); err != nil {
			t.Fatal(err)
		}
	}
	if err := tw.Close(); err != nil {
		t.Fatal(err)
	}
	if err := gz.Close(); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(dir, file)
	if err := os.WriteFile(path, buf.Bytes(), 0o600); err != nil {
		t.Fatal(err)
	}
	return path
}

func TestExtractBinaryZipSlip(t *testing.T) {
	dir := t.TempDir()
	// 归档含 ../ 逃逸条目：提取必须整体拒绝。
	evil := buildTarGz(t, dir, "evil.tar.gz", []tarEntry{
		{name: "kvmcloud-control", body: "binary"},
		{name: "../../etc/passwd", body: "evil"},
	})
	if err := extractBinary(evil, dir, "kvmcloud-control"); err == nil {
		t.Fatal("zip-slip entry must be rejected")
	}
	// 常规归档：单二进制条目成功提取且内容一致。
	clean := buildTarGz(t, dir, "clean.tar.gz", []tarEntry{{name: "kvmcloud-control", body: "binary"}})
	if err := extractBinary(clean, dir, "kvmcloud-control"); err != nil {
		t.Fatalf("clean archive: %v", err)
	}
	data, err := os.ReadFile(filepath.Join(dir, "kvmcloud-control"))
	if err != nil || string(data) != "binary" {
		t.Fatalf("extracted content wrong: %q err=%v", data, err)
	}
	// 缺失目标二进制必须报错。
	missing := buildTarGz(t, dir, "missing.tar.gz", []tarEntry{{name: "other-file", body: "x"}})
	if err := extractBinary(missing, dir, "kvmcloud-control"); err == nil {
		t.Fatal("missing binary must fail")
	}
}
