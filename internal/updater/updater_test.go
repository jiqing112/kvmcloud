func mustURL(t *testing.T, raw string) *http.Request {
	t.Helper()
	req, err := http.NewRequest(http.MethodGet, raw, nil)
	if err != nil {
		t.Fatal(err)
	}
	return req
}

func TestParseVersion(t *testing.T) {
	cases := []struct {
		in   string
		want [3]uint64
		ok   bool
	}{
		{"v0.2.1", [3]uint64{0, 2, 1}, true},
		{"1.10.3", [3]uint64{1, 10, 3}, true},
		{"v1.0.0", [3]uint64{1, 0, 0}, true},
		{"dev", [3]uint64{}, false},
		{"v1.2", [3]uint64{}, false},
		{"v1.2.3-rc1", [3]uint64{}, false}, // 与 install.sh 同口径：仅接受三段数字
		{"v1.2.3.4", [3]uint64{}, false},
		{"../evil", [3]uint64{}, false},
		{"", [3]uint64{}, false},
	}
	for _, c := range cases {
		got, ok := ParseVersion(c.in)
		if ok != c.ok {
			t.Fatalf("ParseVersion(%q) ok=%v, want %v", c.in, ok, c.ok)
		}
		if ok && got != (Version{c.want[0], c.want[1], c.want[2]}) {
			t.Fatalf("ParseVersion(%q) = %v, want %v", c.in, got, c.want)
		}
	}
}

func TestCompare(t *testing.T) {
	less := [][2]string{
		{"v0.2.1", "v0.2.2"},
		{"v0.2.1", "v0.3.0"},
		{"v0.2.9", "v0.10.0"},
		{"v1.0.0", "v1.0.1"},
		{"v9.9.9", "v10.0.0"},
	}
	for _, c := range less {
		a, okA := ParseVersion(c[0])
		b, okB := ParseVersion(c[1])
		if !okA || !okB {
			t.Fatalf("parse failed: %v", c)
		}
		if Compare(a, b) >= 0 {
			t.Fatalf("expected %s < %s", c[0], c[1])
		}
		if Compare(b, a) <= 0 {
			t.Fatalf("expected %s > %s", c[1], c[0])
		}
	}
	eq, _ := ParseVersion("v1.2.3")
	same, _ := ParseVersion("1.2.3")
	if Compare(eq, same) != 0 {
		t.Fatal("expected equal versions")
	}
}

func TestParseChecksums(t *testing.T) {
	text := `# generated by goreleaser
3f5a8b2c9d0e1f2a3b4c5d6e7f8091a2b3c4d5e6f708192a3b4c5d6e7f8091a2  kvmcloud-control_linux_amd64.tar.gz
ABCDEF0123456789abcdef0123456789abcdef0123456789abcdef0123456789 *kvmcloud-agent_linux_amd64.tar.gz
`
	sums, err := parseChecksums(text)
	if err != nil {
		t.Fatalf("parseChecksums: %v", err)
	}
	if got := sums["kvmcloud-control_linux_amd64.tar.gz"]; len(got) != 64 || got != strings.ToLower(got) {
		t.Fatalf("control entry bad: %q", got)
	}
	if got := sums["kvmcloud-agent_linux_amd64.tar.gz"]; got != "abcdef0123456789abcdef0123456789abcdef0123456789abcdef0123456789" {
		t.Fatalf("agent entry bad: %q", got)
	}
	if _, err = parseChecksums("not-a-checksum-line"); err == nil {
		t.Fatal("expected invalid line rejection")
	}
	if _, err = parseChecksums("# only comments"); err == nil {
		t.Fatal("expected empty rejection")
	}
}

func TestAllowedHost(t *testing.T) {
	allowed := []string{
		"gitee.com", "api.gitee.com",
		"github.com", "api.github.com",
		"raw.githubusercontent.com", "objects.githubusercontent.com",
	}
	denied := []string{
		"127.0.0.1", "localhost", "internal.local", "evil.com",
		"gitee.com.evil.com", "", "notgitee.com",
	}
	for _, h := range allowed {
		if !allowedHost(h) {
			t.Fatalf("host %q should be allowed", h)
		}
	}
	for _, h := range denied {
		if allowedHost(h) {
			t.Fatalf("host %q should be denied", h)
		}
	}
}

